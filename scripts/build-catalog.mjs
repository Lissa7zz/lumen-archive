import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  artworks,
  homepageArtworkIds
} from "../src/data/catalog.js";

const root = path.resolve(import.meta.dirname, "..");
const dataDir = path.join(root, "public", "data");
const chunkDir = path.join(dataDir, "chunks");
const curatedPath = path.join(root, "src", "data", "artworks.js");
const pageSize = 12;
const chunkSize = 10;

const sortedWorks = [...artworks].sort(
  (first, second) =>
    first.year - second.year ||
    first.titleZh.localeCompare(second.titleZh, "zh-CN")
);

const curatedWorks = homepageArtworkIds.map((id) => {
  const work = sortedWorks.find((candidate) => candidate.id === id);
  if (!work) throw new Error(`Homepage artwork not found: ${id}`);
  return work;
});

if (curatedWorks.length !== pageSize) {
  throw new Error(`Homepage selection must contain exactly ${pageSize} works`);
}

const curatedSource = `// Generated by scripts/build-catalog.mjs. Do not edit by hand.
export const artworks = ${JSON.stringify(curatedWorks, null, 2)};

export const worksByYear = [...artworks].sort((a, b) => a.year - b.year);

export const featuredArtwork = artworks.find((work) => work.id === "night-watch");
`;

await writeFile(curatedPath, curatedSource);
await rm(chunkDir, { recursive: true, force: true });
await mkdir(chunkDir, { recursive: true });

const chunks = [];
for (let offset = 0; offset < sortedWorks.length; offset += chunkSize) {
  const number = chunks.length + 1;
  const fileName = `works-${String(number).padStart(3, "0")}.json`;
  const works = sortedWorks.slice(offset, offset + chunkSize);
  await writeFile(
    path.join(chunkDir, fileName),
    `${JSON.stringify(works, null, 2)}\n`
  );
  chunks.push({
    file: `data/chunks/${fileName}`,
    count: works.length,
    firstYear: works[0].year,
    lastYear: works.at(-1).year
  });
}

const searchIndex = [];
sortedWorks.forEach((work, index) => {
  searchIndex.push({
    id: work.id,
    chunk: Math.floor(index / chunkSize) + 1,
    text: [
      work.titleZh,
      work.titleEn,
      work.artist,
      work.artistEn,
      work.year,
      work.medium,
      work.mediumDetail,
      work.origin,
      work.collection,
      work.description
    ]
      .join(" ")
      .toLocaleLowerCase("zh-CN")
  });
});

const manifest = {
  total: sortedWorks.length,
  curatorial: curatedWorks.length,
  pageSize,
  chunkSize,
  chunks
};

await writeFile(
  path.join(dataDir, "manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`
);
await writeFile(
  path.join(dataDir, "search-index.json"),
  `${JSON.stringify(searchIndex)}\n`
);

console.log(
  `Generated ${curatedWorks.length} homepage works, ${chunks.length} data chunks, ` +
    `and a ${searchIndex.length}-record search index`
);
