function makeWork(data) {
  const work = {
    medium: "绘画与版画",
    license: "Public domain",
    licenseUrl: "https://creativecommons.org/publicdomain/mark/1.0/",
    ratio: "landscape",
    layout: "standard",
    accent: "#9a8062",
    ...data
  };

  return {
    ...work,
    slug: work.slug ?? work.id,
    sourcePage:
      data.sourcePage ??
      `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(
        data.sourceFile.replaceAll(" ", "_")
      )
        .replaceAll("(", "%28")
        .replaceAll(")", "%29")
        .replaceAll("'", "%27")}`,
    attribution:
      data.attribution ??
      `${data.artistEn}, ${work.license}, via Wikimedia Commons`
  };
}

